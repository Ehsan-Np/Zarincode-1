/**
 * Copy for the composed demo pages.
 *
 * `Page_Composer` only knows *how* a page is assembled (containers + native
 * widgets); this file knows *what* it says. Keeping the two apart means the
 * page copy can be reviewed, translated or replaced without touching the
 * builder, and it is obvious where a client string lives.
 *
 * Every array below is the exact input of `Page_Composer::inner()`:
 *
 *   badge, title, lead          → the page hero (H1 + intro)
 *   primary / secondary         → hero buttons [text, url]
 *   sections[]                  → heading + lead + a grid of icon-box cards
 *   nodes[]                     → pre-built blocks (real product/post/project grids)
 *   clauses[]                   → legal document clauses (title + html)
 *   cta                         → closing call to action
 *
 * Copy follows the studio's own rules: concrete, no invented statistics, no
 * promise the team cannot keep, and a clear next step on every page.
 *
 * @package Zarincode\Runtime260\Demo
 */

