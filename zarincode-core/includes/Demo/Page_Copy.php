	 * Homepage content, section by section.
	 *
	 * The theme owns the canonical homepage copy in
	 * `zarincode/inc/Home/home-content.json`; it is read here so the composed
	 * page and the widget defaults can never drift apart.
	 *
	 * @return array<string, array>
	 */
	public static function home(): array {
		$sections = array( 'hero', 'partners', 'services', 'products', 'portfolio', 'why', 'steps', 'pricing', 'testimonials', 'blog', 'promo' );
		$out      = array();
		foreach ( $sections as $key ) {
			$defaults = class_exists( '\Zarincode\Theme\Home\Home_Templates' )
				? \Zarincode\Theme\Home\Home_Templates::defaults( $key )
				: array();
			if ( $defaults ) {
				$out[ $key ] = $defaults;
			}
		}
		return $out;
	}

