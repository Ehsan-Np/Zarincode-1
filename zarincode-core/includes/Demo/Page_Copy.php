		);
	}

	/* ---------------------------------------------------------------------
	 * Non-Elementor fallback
	 * ------------------------------------------------------------------ */

	/**
	 * Plain HTML body for the page, used only when Elementor is not rendering
	 * (deactivated or previewing `post_content`). It never competes with the
	 * composed document: it is the same copy, without the design.
	 */
	public static function plain( array $page ): string {
		$html = '';
		if ( ! empty( $page['title'] ) ) {
			$html .= '<h1>' . esc_html( (string) $page['title'] ) . '</h1>';
		}
		if ( ! empty( $page['lead'] ) ) {
			$html .= '<p>' . wp_kses_post( (string) $page['lead'] ) . '</p>';
		}
		foreach ( (array) ( $page['sections'] ?? array() ) as $section ) {
			if ( ! empty( $section['title'] ) ) {
				$html .= '<h2>' . esc_html( (string) $section['title'] ) . '</h2>';
			}
			if ( ! empty( $section['lead'] ) ) {
				$html .= '<p>' . wp_kses_post( (string) $section['lead'] ) . '</p>';
			}
			if ( ! empty( $section['cards'] ) ) {
				$html .= '<ul>';
				foreach ( (array) $section['cards'] as $card ) {
					$html .= '<li><strong>' . esc_html( (string) ( $card['title'] ?? '' ) ) . '</strong> — ' . esc_html( (string) ( $card['text'] ?? '' ) ) . '</li>';
				}
				$html .= '</ul>';
			}
			if ( ! empty( $section['html'] ) ) {
				$html .= wp_kses_post( (string) $section['html'] );
			}
		}
		foreach ( (array) ( $page['clauses'] ?? array() ) as $clause ) {
			$html .= '<h2>' . esc_html( (string) ( $clause['title'] ?? '' ) ) . '</h2>' . wp_kses_post( (string) ( $clause['html'] ?? '' ) );
		}
		return $html;
	}
