	/**
	 * One legal page, composed from the clause list of `service-demo.json`.
	 *
	 * Clauses are real Elementor widgets (heading + text editor per clause),
	 * so the owner can rewrite any single clause without touching the rest.
	 */
	public static function legal( string $slug, string $title, string $lead ): array {
		$data    = Service_Demo::legal_data( $slug );
		$clauses = array();
		foreach ( (array) ( $data['sections'] ?? array() ) as $part ) {
			$clauses[] = array(
				'title' => (string) ( $part[0] ?? '' ),
				'html'  => '<p>' . wp_kses_post( (string) ( $part[1] ?? '' ) ) . '</p>',
			);
		}
		return array(
			'badge'   => 'LEGAL · نسخهٔ نمایشی سند',
			'title'   => $title,
			'lead'    => $lead,
			'clauses' => $clauses,
			'cta'     => array(
				'title'   => 'برای پرسش دربارهٔ این سند با ما در تماس باشید',
				'text'    => 'این متن نسخهٔ نمایشی است و پیش از انتشار باید با سیاست واقعی کسب‌وکار و مشاور حقوقی تطبیق داده شود. برای پرسش دربارهٔ بندها، شمارهٔ بند را ذکر کنید.',
