			),
			array(
				'label'  => 'پوشاندن مسیر مطلق در پیام‌ها',
				'state'  => 'ok',
				'detail' => 'هر پیامی که به مرورگر برمی‌گردد از Hardening::scrub() می‌گذرد؛ مسیرهایی مثل /home/…/public_html حذف می‌شوند.',
			),
			array(
				'label'  => 'پشتیبانی از مسیر سایت در wp_die',
				'state'  => 'ok',
				'detail' => 'صفحهٔ خطای وردپرس نیز پیش از نمایش پاک‌سازی می‌شود.',
