		$guard   = (string) get_option( 'zarincode_debug_log_guard', '' );
		$logfile = defined( 'WP_DEBUG_LOG' ) && is_string( WP_DEBUG_LOG ) ? WP_DEBUG_LOG : ( defined( 'WP_CONTENT_DIR' ) ? WP_CONTENT_DIR . '/debug.log' : '' );

		$rows = array(
			array(
				'label'  => 'نمایش خطای PHP به بازدیدکننده',
				'state'  => in_array( $display, array( '0', 'off', '' ), true ) ? 'ok' : 'warn',
				'detail' => in_array( $display, array( '0', 'off', '' ), true )
					? 'خاموش است؛ پیام خطا هرگز همراه مسیر فایل نمایش داده نمی‌شود.'
					: 'در php.ini هاست روشن است، اما لایهٔ مهار خطا در افزونه نمایش خطاهای غیرکشنده را می‌گیرد.',
			),
