			),
			array(
				'label'  => 'لیست کاربران با ?author=',
				'state'  => 'ok',
				'detail' => 'برای بازدیدکنندگان مهمان به صفحهٔ اصلی هدایت می‌شود؛ مسیر /wp/v2/users نیز بسته است.',
			),
			array(
				'label'  => 'هدرهای امنیتی',
				'state'  => 'ok',
				'detail' => 'X-Content-Type-Options، Referrer-Policy، X-Frame-Options، Permissions-Policy، Cross-Origin-Resource-Policy و حذف X-Powered-By.',
			),
			array(
				'label'  => 'ویرایشگر فایل در پیشخوان',
				'state'  => ( defined( 'DISALLOW_FILE_EDIT' ) && DISALLOW_FILE_EDIT ) ? 'ok' : 'warn',
				'detail' => ( defined( 'DISALLOW_FILE_EDIT' ) && DISALLOW_FILE_EDIT )
					? 'غیرفعال است.'
