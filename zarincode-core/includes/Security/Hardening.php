		return $rows;
	}

	/**
	 * Are the auth salts defined with distinct values?
	 *
	 * @return bool
	 */
	private static function salts_ok(): bool {
		$keys   = array( 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' );
		$values = array();
		foreach ( $keys as $key ) {
			if ( ! defined( $key ) ) {
				return false;
			}
			$value = (string) constant( $key );
			if ( strlen( $value ) < 32 || false !== strpos( $value, 'put your unique phrase here' ) ) {
				return false;
			}
			$values[] = $value;
		}
		return count( array_unique( $values ) ) === count( $values );
	}
