				'state'  => 'done' === $guard ? 'ok' : ( 'failed' === $guard || ( '' !== $logfile && file_exists( $logfile ) ) ? 'warn' : 'ok' ),
				'detail' => 'done' === $guard ? 'قاعدهٔ مسدودسازی در wp-content/.htaccess نوشته شد.' : 'اگر فایل لاگ در دسترس وب است، بهتر است مسیر آن به بیرون از public_html منتقل شود.',
			),
			array(
