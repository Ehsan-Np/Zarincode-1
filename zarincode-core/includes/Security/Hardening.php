<?php
/**
 * Security hardening — error display, path leaks and basic attack surface.
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * The site showed this on a live page:
 *
 *   Warning: strpos(): Passing null to parameter #1 ($haystack) ...
 *   in /home/greenfis/public_html/wp-content/themes/zarincode/header.php on line 54
 *
 * Two independent things had to be true for that to happen:
 *
 *  1. one line of our code emitted a PHP notice (a `null` passed to strpos());
 *  2. PHP was configured with `display_errors = On`, so PHP printed the notice
 *     — and PHP always prints the *absolute filesystem path* of the file in an
 *     error message. The path is not stored anywhere by WordPress; it is
 *     generated by PHP itself at the moment it renders the error.
 *
 * (1) is fixed in the theme (header.php passes a string, guarded with
 * `is_string()`). But (2) is host configuration we do not control: shared
 * hosts often ship `display_errors = On` and `php_admin_flag` cannot be
 * overridden with `ini_set()`. Therefore the project no longer relies on
 * configuration alone:
 *
 *  - `shield_errors()` turns display off when possible **and** installs an
 *    error handler that swallows the display of every non-fatal error. That
 *    handler works even when the host forces `display_errors = On`, because the
 *    error never reaches PHP's internal (printing) handler.
 *  - `scrub()` is the single place that strips absolute paths, document root
 *    and plugin/theme directories out of any message that we hand back to a
 *    browser (AJAX responses, admin notices, installer errors). Messages from
 *    `unzip_file()` / `WP_Error` routinely contain `/home/.../public_html/...`.
 *  - `audit()` feeds the admin panel so the state is verifiable instead of
 *    assumed.
 *
 * The class is loaded straight from the plugin bootstrap (before `init`), so
 * the shield is in place for the whole request.
 *
 * @package Zarincode
 */

namespace Zarincode\Runtime260\Security;

defined( 'ABSPATH' ) || exit;

/**
 * Error shield, path scrubber and HTTP hardening.
 */
final class Hardening {

	/**
	 * True once the instance booted, so the theme fallback does not double-register.
	 *
	 * @var bool
	 */
	private static bool $booted = false;

	/**
	 * Previous error handler, if there was one.
	 *
	 * @var callable|null
	 */
	private static $previous_handler = null;

	/**
	 * Boot everything. Safe to call more than once.
	 */
	public static function boot(): void {
		if ( self::$booted ) {
			return;
		}
		self::$booted = true;

		self::shield_errors();

		// WordPress' own fatal-error page can be filtered; make sure it never
		// contains a server path either.
		add_filter( 'wp_php_error_message', array( __CLASS__, 'scrub' ) );
		add_filter( 'wp_die_handler', array( __CLASS__, 'filter_die_handler' ) );

		add_action( 'send_headers', array( __CLASS__, 'send_headers' ) );
		add_action( 'init', array( __CLASS__, 'reduce_fingerprint' ), 1 );
		add_action( 'init', array( __CLASS__, 'block_author_enumeration' ), 1 );
		add_action( 'init', array( __CLASS__, 'protect_debug_log' ), 1 );
		add_filter( 'rest_endpoints', array( __CLASS__, 'restrict_users_endpoint' ) );
	}

	/* ------------------------------------------------------------------ *
	 * 1. Error display
	 * ------------------------------------------------------------------ */

	/**
	 * Is showing PHP errors to visitors allowed on this install?
	 *
	 * Off by default: a notice must never be rendered into a page. Developers
	 * who want to see errors in the browser can opt in with
	 *
	 *   add_filter( 'zarincode_display_php_errors', '__return_true' );
	 *
	 * @return bool
	 */
	public static function display_errors_allowed(): bool {
		$allowed = (bool) apply_filters( 'zarincode_display_php_errors', false );

		// Never show errors on a public request, whatever a developer asked for,
		// unless the request is local.
		if ( $allowed && ! self::is_local_request() ) {
			$allowed = false;
		}

		return $allowed;
	}

	/**
	 * Local (development) request?
	 *
	 * @return bool
	 */
	private static function is_local_request(): bool {
		$host = isset( $_SERVER['HTTP_HOST'] ) ? (string) wp_unslash( $_SERVER['HTTP_HOST'] ) : '';
		if ( '' === $host && defined( 'WP_CLI' ) && WP_CLI ) {
			return true;
		}
		$name = strtolower( (string) wp_parse_url( 'http://' . $host, PHP_URL_HOST ) );

		return in_array( $name, array( 'localhost', '127.0.0.1', '::1' ), true )
			|| (bool) preg_match( '/\.(local|test|localhost)$/', $name );
	}

	/**
	 * Stop PHP from printing errors (with their absolute file paths).
	 */
	private static function shield_errors(): void {
		// Keep logging: the information must still reach the server log.
		if ( '0' !== ini_get( 'log_errors' ) || false === ini_get( 'log_errors' ) ) {
			@ini_set( 'log_errors', '1' ); // phpcs:ignore WordPress.PHP.IniSet.Risky -- logging stays on; only display is being changed.
		}

		if ( self::display_errors_allowed() ) {
			return;
		}

		// Layer 1: configuration (works on most hosts).
		@ini_set( 'display_errors', '0' );          // phpcs:ignore WordPress.PHP.IniSet.display_errors_Blacklisted
		@ini_set( 'display_startup_errors', '0' );  // phpcs:ignore WordPress.PHP.IniSet.Risky
		@ini_set( 'html_errors', '0' );             // phpcs:ignore WordPress.PHP.IniSet.Risky

		// Layer 2: handler. This is what also covers hosts that pin
		// `display_errors On` with php_admin_flag, where ini_set() is a no-op:
		// returning true means PHP's printing handler never runs.
		self::$previous_handler = set_error_handler( array( __CLASS__, 'handle_error' ) ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_set_error_handler
	}

	/**
	 * Log non-fatal errors ourselves instead of letting PHP print them.
	 *
	 * Fatal errors are not handled here (PHP does not call error handlers for
	 * them); WordPress' fatal-error handler renders a safe page for those.
	 *
	 * @param int    $number  Error level.
	 * @param string $message Message.
	 * @param string $file    File.
	 * @param int    $line    Line.
	 * @return bool True = handled, do not run PHP's internal (printing) handler.
	 */
	public static function handle_error( $number, $message, $file = '', $line = 0 ): bool {
		// Respect @-suppression and error_reporting(): do nothing if muted.
		if ( ! ( error_reporting() & $number ) ) { // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_reporting_Ok
			return false;
		}

		// Fatals that PHP does route through user handlers: log, then let the
		// normal (fatal) path continue so WordPress can render its safe page.
		$fatal = in_array( $number, array( E_USER_ERROR, E_RECOVERABLE_ERROR ), true );

		$labels = array(
			E_ERROR             => 'Fatal error',
			E_WARNING           => 'Warning',
			E_PARSE             => 'Parse error',
			E_NOTICE            => 'Notice',
			E_CORE_ERROR        => 'Core error',
			E_CORE_WARNING      => 'Core warning',
			E_COMPILE_ERROR     => 'Compile error',
			E_COMPILE_WARNING   => 'Compile warning',
			E_USER_ERROR        => 'User error',
			E_USER_WARNING      => 'User warning',
			E_USER_NOTICE       => 'User notice',
			E_RECOVERABLE_ERROR => 'Recoverable error',
			E_DEPRECATED        => 'Deprecated',
			E_USER_DEPRECATED   => 'User deprecated',
		);
		$label  = $labels[ $number ] ?? 'PHP';

		// Log the scrubbed message: even the server log must not be the place
		// somebody copies a path from into a ticket.
		$rel = self::relative_path( (string) $file );
		error_log( sprintf( 'Zarincode %s: %s in %s:%d', $label, self::scrub( (string) $message ), $rel, (int) $line ) ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log

		return true;
	}

	/**
	 * Make `wp_die()` (used by core for DB/fatal errors) path-free as well.
	 *
	 * @param callable $handler Current handler.
	 * @return callable
	 */
	public static function filter_die_handler( $handler ) {
		if ( ! is_callable( $handler ) ) {
			return $handler;
		}

		return static function ( $message, $title = '', $args = array() ) use ( $handler ) {
			if ( is_string( $message ) ) {
				$message = Hardening::scrub( $message );
			}
			return $handler( $message, $title, $args );
		};
	}

	/* ------------------------------------------------------------------ *
	 * 2. Path scrubbing
	 * ------------------------------------------------------------------ */

	/**
	 * Remove absolute filesystem paths from a message that will be displayed.
	 *
	 * @param string $text Message.
	 * @return string
	 */
	public static function scrub( $text ): string {
		$text = (string) $text;
		if ( '' === $text ) {
			return '';
		}

		$needles = array();
		foreach ( array( 'ABSPATH', 'WP_CONTENT_DIR', 'WP_PLUGIN_DIR', 'WPMU_PLUGIN_DIR', 'TEMPLATEPATH', 'STYLESHEETPATH' ) as $constant ) {
			if ( defined( $constant ) ) {
				$value = (string) constant( $constant );
				if ( strlen( $value ) > 1 ) {
					$needles[] = untrailingslashit( $value );
				}
			}
		}
		if ( function_exists( 'get_template_directory' ) ) {
			$needles[] = untrailingslashit( (string) get_template_directory() );
		}
		if ( function_exists( 'get_stylesheet_directory' ) ) {
			$needles[] = untrailingslashit( (string) get_stylesheet_directory() );
		}
		if ( defined( 'ZARINCODE_CORE_PATH' ) ) {
			$needles[] = untrailingslashit( (string) ZARINCODE_CORE_PATH );
		}

		// Longest first, so `/…/public_html/wp-content/themes/zarincode` is
		// replaced before `/…/public_html`.
		$needles = array_unique( array_filter( $needles, static fn( $n ) => is_string( $n ) && strlen( $n ) > 3 ) );
		usort( $needles, static fn( $a, $b ) => strlen( $b ) <=> strlen( $a ) );

		// A known root is replaced by the *file name* only, so a log line such as
		// "in /home/x/public_html/wp-content/themes/zarincode/header.php:54"
		// becomes "in header.php:54" — still useful, without the server layout.
		// Character classes use \x27 / \x22 instead of quote characters so the
		// pattern survives single-quoted PHP strings unchanged.
		foreach ( $needles as $needle ) {
			foreach ( array( $needle, str_replace( '/', '\\', $needle ) ) as $variant ) {
				$pattern = '#' . preg_quote( $variant, '#' ) . '([^\s\x27\x22<>]*?)(?::(\d+))?(?=[\s\x27\x22<>]|$)#';
				$text    = (string) preg_replace_callback(
					$pattern,
					static function ( $m ) {
						$tail = str_replace( '\\', '/', (string) ( $m[1] ?? '' ) );
						$name = '' !== $tail ? basename( $tail ) : '';
						$line = isset( $m[2] ) && '' !== $m[2] ? ':' . $m[2] : '';
						return $name . $line;
					},
					$text
				);
			}
		}

		// Roots we do not know (another site on the same host, C:\inetpub\…):
		// drop the directory chain together with the line number.
		$text = (string) preg_replace(
			'#(?:[A-Za-z]:\\\\|/)(?:home|var|www|usr|srv|opt|inetpub|Users|private)(?:[\\\\/][^\s\x27\x22<>]+)+(?::\d+)?#i',
			'',
			$text
		);

		// Collapse the artifacts the replacements leave behind.
		$text = (string) preg_replace( '#\s{2,}#', ' ', $text );
		$text = (string) preg_replace( '#\bin\s+:?(\d+)#', 'in line $1', $text );
		$text = (string) preg_replace( '#\s+([,.;:])#', '$1', $text );

		return trim( $text );
	}

	/**
	 * Path of a file relative to the WordPress root (for logs, never for output).
	 *
	 * @param string $file Absolute path.
	 * @return string
	 */
	public static function relative_path( string $file ): string {
		$root = defined( 'ABSPATH' ) ? untrailingslashit( (string) ABSPATH ) : '';
		$file = wp_normalize_path( $file );
		if ( '' !== $root ) {
			$root = wp_normalize_path( $root );
			if ( 0 === strpos( $file, $root . '/' ) ) {
				return ltrim( substr( $file, strlen( $root ) ), '/' );
			}
		}
		$name = basename( $file );
		return '' !== $name ? $name : '(internal)';
	}

	/* ------------------------------------------------------------------ *
	 * 3. HTTP surface
	 * ------------------------------------------------------------------ */

	/**
	 * Security headers + remove the PHP fingerprint.
	 */
	public static function send_headers(): void {
		if ( is_admin() && ! wp_doing_ajax() ) {
			// The admin already sends its own frame/CSP related headers; adding
			// X-Frame-Options here could break screen options in some browsers.
			return;
		}

		if ( ! headers_sent() ) {
			header_remove( 'X-Powered-By' );
			header( 'X-Content-Type-Options: nosniff' );
			header( 'Referrer-Policy: strict-origin-when-cross-origin' );
			header( 'X-Frame-Options: SAMEORIGIN' );
			// Microphone stays enabled for same origin: the live chat records
			// voice messages with getUserMedia().
			header( 'Permissions-Policy: camera=(self), microphone=(self), geolocation=()' );
			header( 'Cross-Origin-Resource-Policy: same-site' );
		}
	}

	/**
	 * Stop advertising the WordPress/PHP version.
	 */
	public static function reduce_fingerprint(): void {
		remove_action( 'wp_head', 'wp_generator' );
		remove_action( 'wp_head', 'rsd_link' );
		remove_action( 'wp_head', 'wlwmanifest_link' );
		remove_action( 'wp_head', 'wp_shortlink_wp_head' );
		remove_action( 'template_redirect', 'wp_shortlink_header', 11 );
		add_filter( 'the_generator', '__return_empty_string' );

		// XML-RPC: not used by the theme, but it is the classic brute-force and
		// pingback-reflection entry point. Elementor and WooCommerce do not use it.
		add_filter( 'xmlrpc_enabled', '__return_false' );
		add_filter( 'wp_headers', static function ( $headers ) {
			unset( $headers['X-Pingback'] );
			return $headers;
		} );
	}

	/**
	 * `?author=1` redirects to the nicename and leaks admin login names.
	 */
	public static function block_author_enumeration(): void {
		if ( is_admin() || wp_doing_ajax() || ( defined( 'REST_REQUEST' ) && REST_REQUEST ) ) {
			return;
		}
		// phpcs:disable WordPress.Security.NonceVerification.Recommended -- read-only probe of a public URL.
		if ( ! isset( $_GET['author'] ) || is_user_logged_in() ) {
			return;
		}
		// phpcs:enable WordPress.Security.NonceVerification.Recommended
		wp_safe_redirect( home_url( '/' ), 301 );
		exit;
	}

	/**
	 * Remove the public author archive from the REST API (user list / login names).
	 *
	 * @param array $endpoints Registered routes.
	 * @return array
	 */
	public static function restrict_users_endpoint( $endpoints ) {
		if ( is_user_logged_in() || ! is_array( $endpoints ) ) {
			return $endpoints;
		}
		foreach ( array_keys( $endpoints ) as $route ) {
			if ( 0 === strpos( (string) $route, '/wp/v2/users' ) ) {
				unset( $endpoints[ $route ] );
			}
		}
		return $endpoints;
	}

	/**
	 * `wp-content/debug.log` is world readable on most Apache/LiteSpeed hosts:
	 * it repeats every notice with its absolute path. Deny it when the server
	 * allows per-directory rules and we can write them; otherwise the audit
	 * panel reports it so the file can be moved.
	 */
	public static function protect_debug_log(): void {
		if ( ! function_exists( 'get_option' ) ) {
			return;
		}
		if ( 'done' === get_option( 'zarincode_debug_log_guard' ) ) {
			return;
		}
		if ( ! defined( 'WP_CONTENT_DIR' ) || ! is_dir( WP_CONTENT_DIR ) || ! is_writable( WP_CONTENT_DIR ) ) {
			return;
		}
		if ( ! function_exists( 'got_url_rewrite' ) && ! file_exists( WP_CONTENT_DIR . '/.htaccess' ) ) {
			return;
		}

		$marker = '# BEGIN Zarincode log guard';
		$path   = WP_CONTENT_DIR . '/.htaccess';
		$rules  = $marker . "\n"
			. "<FilesMatch \"^(debug|error|php|fatal)[-_]?\\.log$\">\n"
			. "\t<IfModule mod_authz_core.c>\n\t\tRequire all denied\n\t</IfModule>\n"
			. "\t<IfModule !mod_authz_core.c>\n\t\tOrder allow,deny\n\t\tDeny from all\n\t</IfModule>\n"
			. "</FilesMatch>\n"
			. '# END Zarincode log guard' . "\n";

		$existing = file_exists( $path ) ? (string) file_get_contents( $path ) : ''; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- local server config file.
		if ( false !== strpos( $existing, $marker ) ) {
			update_option( 'zarincode_debug_log_guard', 'done', false );
			return;
		}

		$written = @file_put_contents( $path, ( '' === $existing ? '' : rtrim( $existing ) . "\n\n" ) . $rules ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents, WordPress.PHP.NoSilencedErrors.Discouraged -- best effort server config, failure handled below.
		update_option( 'zarincode_debug_log_guard', $written ? 'done' : 'failed', false );
	}

